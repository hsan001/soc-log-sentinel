"""
engine.py - Detection & Rule Evaluation Engine
=============================================
Loads Sigma-inspired YAML detection rules, compiles regex patterns with ReDoS guards,
evaluates streaming log entries, and maps threats to MITRE ATT&CK techniques and Navigator layers.
"""

from __future__ import annotations

import glob
import json
import logging
import os
import re
from collections import defaultdict
from dataclasses import dataclass, field
from typing import Any, Dict, Iterable, List, Optional

from .parser import LogEntry

logger = logging.getLogger("sentinel.engine")

MAX_REGEX_EVAL_LENGTH = 10_000  # Cap string length for regex evaluation to prevent ReDoS

# Tactic normalization map for MITRE ATT&CK Navigator layers
TACTIC_NAVIGATOR_MAP = {
    "initial access": "initial-access",
    "execution": "execution",
    "persistence": "persistence",
    "privilege escalation": "privilege-escalation",
    "defense evasion": "defense-evasion",
    "credential access": "credential-access",
    "discovery": "discovery",
    "lateral movement": "lateral-movement",
    "collection": "collection",
    "command and control": "command-and-control",
    "exfiltration": "exfiltration",
    "impact": "impact",
}

SEVERITY_SCORE_MAP = {
    "Critical": (95, "0.95", "#ef4444"),
    "High": (80, "0.85", "#f97316"),
    "Medium": (60, "0.70", "#eab308"),
    "Low": (40, "0.50", "#3b82f6"),
    "Informational": (20, "0.30", "#6b7280"),
}


# Safe YAML loader supporting both PyYAML and ruamel.yaml
def _safe_yaml_load(content: str) -> Dict[str, Any]:
    try:
        import yaml
        return yaml.safe_load(content) or {}
    except ImportError:
        try:
            from ruamel.yaml import YAML
            ruamel_loader = YAML(typ='safe')
            return ruamel_loader.load(content) or {}
        except ImportError:
            raise ImportError("Neither 'PyYAML' nor 'ruamel.yaml' is installed.")


@dataclass
class Rule:
    """Detection rule specification aligned with MITRE ATT&CK."""
    id: str
    name: str
    description: str
    severity: str  # Critical, High, Medium, Low
    log_type: str  # auth, web, windows, all
    mitre_id: str
    mitre_technique: str
    mitre_tactic: str
    detection_type: str  # 'pattern' or 'threshold'
    action: Optional[str] = None
    target_field: Optional[str] = None  # target, command_line, raw, user
    patterns: List[re.Pattern] = field(default_factory=list)
    threshold: int = 1
    group_by: str = "source_ip"  # 'source_ip' or 'user'
    remediation: str = ""
    raw: Dict[str, Any] = field(default_factory=dict)


@dataclass
class Alert:
    """Security Incident Alert generated by rule evaluation."""
    alert_id: str
    rule_id: str
    rule_name: str
    severity: str
    source_ip: str
    target: str
    user: str
    mitre_id: str
    mitre_technique: str
    mitre_tactic: str
    description: str
    evidence: str
    count: int
    timestamp: str
    remediation: str


SEVERITY_ORDER = {
    "Critical": 4,
    "High": 3,
    "Medium": 2,
    "Low": 1,
    "Informational": 0
}


def is_potential_redos(pattern_str: str) -> bool:
    """Detect common dangerous nested quantifier constructs prone to catastrophic backtracking."""
    # Check for nested quantifiers like (a+)+, (.*a)+, ([a-z]+)*, etc.
    return bool(re.search(r'(\+|\*|\{[0-9]+,\})\)[+*]', pattern_str))


class DetectionEngine:
    """Engine that loads YAML detection rules and evaluates streaming LogEntry events."""

    def __init__(self, rules_dir: Optional[str] = None, brute_force_threshold: int = 5):
        self.rules: List[Rule] = []
        self.default_threshold = brute_force_threshold

        if rules_dir and os.path.exists(rules_dir):
            self.load_rules(rules_dir)

    def load_rules(self, rules_dir: str) -> int:
        """Recursively load and compile YAML rules from directory with ReDoS inspection."""
        self.rules.clear()
        rule_files = glob.glob(os.path.join(rules_dir, "**", "*.yml"), recursive=True) + \
                     glob.glob(os.path.join(rules_dir, "**", "*.yaml"), recursive=True)

        loaded_count = 0
        for rpath in sorted(rule_files):
            try:
                with open(rpath, "r", encoding="utf-8") as f:
                    data = _safe_yaml_load(f.read())

                if not data or not isinstance(data, dict):
                    continue

                rule_id = data.get("id", f"RULE-{loaded_count+1:03d}")
                name = data.get("name", "Unnamed Rule")
                description = data.get("description", "")
                severity = data.get("severity", "Medium")
                log_type = data.get("log_type", "all").lower()

                mitre_info = data.get("mitre", {})
                mitre_id = mitre_info.get("technique_id", "T1000")
                mitre_technique = mitre_info.get("technique_name", "Unknown Technique")
                mitre_tactic = mitre_info.get("tactic", "Unknown Tactic")

                det = data.get("detection", {})
                det_type = det.get("type", "pattern").lower()
                action = det.get("action")
                target_field = det.get("target_field", "target")
                threshold = int(det.get("threshold", 1))
                group_by = det.get("group_by", "source_ip")

                raw_patterns = det.get("patterns", [])
                compiled_patterns = []
                for p in raw_patterns:
                    if is_potential_redos(p):
                        logger.warning(f"Potential ReDoS pattern detected in rule {rule_id}: {p}")
                    try:
                        compiled_patterns.append(re.compile(p, re.IGNORECASE))
                    except re.error as re_err:
                        logger.warning(f"Invalid regex in rule {rule_id}: {p} ({re_err})")

                rule = Rule(
                    id=rule_id,
                    name=name,
                    description=description,
                    severity=severity,
                    log_type=log_type,
                    mitre_id=mitre_id,
                    mitre_technique=mitre_technique,
                    mitre_tactic=mitre_tactic,
                    detection_type=det_type,
                    action=action,
                    target_field=target_field,
                    patterns=compiled_patterns,
                    threshold=threshold,
                    group_by=group_by,
                    remediation=data.get("remediation", ""),
                    raw=data
                )
                self.rules.append(rule)
                loaded_count += 1
            except Exception as e:
                logger.error(f"Error loading rule from {rpath}: {e}")

        logger.info(f"Loaded {loaded_count} detection rules from {rules_dir}")
        return loaded_count

    def analyze_stream(
        self,
        entries: Iterable[LogEntry],
        threshold_override: Optional[int] = None
    ) -> List[Alert]:
        """
        Evaluate normalized log entries against all loaded detection rules.
        Accepts both lists and memory-safe generator streams.
        """
        alerts: List[Alert] = []
        alert_counter = 1

        pattern_matches = defaultdict(list)
        threshold_matches = defaultdict(list)

        for entry in entries:
            for rule in self.rules:
                # Check log type compatibility
                if rule.log_type != "all" and rule.log_type != entry.log_type:
                    # Windows log type also matches sysmon
                    if not (rule.log_type == "windows" and entry.log_type in ("windows", "sysmon")):
                        continue

                if rule.detection_type == "pattern":
                    # Determine text to inspect
                    text_to_check = ""
                    if rule.target_field == "command_line" and entry.command_line:
                        text_to_check = entry.command_line
                    elif rule.target_field == "target":
                        text_to_check = f"{entry.target} {entry.details.get('decoded_uri', '')}"
                    elif rule.target_field == "action":
                        text_to_check = entry.action
                    elif rule.target_field == "user":
                        text_to_check = entry.user
                    else:
                        text_to_check = f"{entry.raw} {entry.target} {entry.command_line or ''}"

                    # ReDoS mitigation: Cap string length and scrub null bytes
                    if len(text_to_check) > MAX_REGEX_EVAL_LENGTH:
                        text_to_check = text_to_check[:MAX_REGEX_EVAL_LENGTH]

                    matched_pattern = None
                    for pat in rule.patterns:
                        m = pat.search(text_to_check)
                        if m:
                            matched_pattern = m.group(0)
                            break

                    if matched_pattern:
                        key = (rule.id, entry.source_ip, entry.target or entry.action)
                        pattern_matches[key].append({
                            "entry": entry,
                            "match": matched_pattern
                        })

                elif rule.detection_type == "threshold":
                    # Check action match
                    if rule.action and entry.action != rule.action:
                        continue

                    group_val = entry.source_ip if rule.group_by == "source_ip" else entry.user
                    key = (rule.id, group_val)
                    threshold_matches[key].append(entry)

        # Build alerts for pattern matches
        for (rule_id, src_ip, target), matches in pattern_matches.items():
            rule = next(r for r in self.rules if r.id == rule_id)
            first_entry = matches[0]["entry"]
            sample_evidence = matches[0]["match"]
            total_count = len(matches)

            alerts.append(Alert(
                alert_id=f"ALT-{alert_counter:03d}",
                rule_id=rule.id,
                rule_name=rule.name,
                severity=rule.severity,
                source_ip=src_ip,
                target=target,
                user=first_entry.user if first_entry.user != "-" else "N/A",
                mitre_id=rule.mitre_id,
                mitre_technique=rule.mitre_technique,
                mitre_tactic=rule.mitre_tactic,
                description=rule.description,
                evidence=sample_evidence,
                count=total_count,
                timestamp=first_entry.timestamp,
                remediation=rule.remediation
            ))
            alert_counter += 1

        # Build alerts for threshold matches
        for (rule_id, group_val), matched_entries in threshold_matches.items():
            rule = next(r for r in self.rules if r.id == rule_id)
            effective_threshold = threshold_override if threshold_override is not None else rule.threshold

            if len(matched_entries) >= effective_threshold:
                first_entry = matched_entries[0]
                target_users = list(dict.fromkeys([e.user for e in matched_entries if e.user and e.user != "-"]))
                user_summary = ", ".join(target_users[:5]) if target_users else group_val

                target_dest = first_entry.target if rule.group_by == "source_ip" else f"User: {group_val}"
                src_ip = group_val if rule.group_by == "source_ip" else first_entry.source_ip

                evidence_summary = f"{len(matched_entries)} failed attempts observed. Sample: {first_entry.raw[:90]}"

                alerts.append(Alert(
                    alert_id=f"ALT-{alert_counter:03d}",
                    rule_id=rule.id,
                    rule_name=rule.name,
                    severity=rule.severity,
                    source_ip=src_ip,
                    target=target_dest,
                    user=user_summary,
                    mitre_id=rule.mitre_id,
                    mitre_technique=rule.mitre_technique,
                    mitre_tactic=rule.mitre_tactic,
                    description=f"{rule.description} ({len(matched_entries)} occurrences exceeding threshold {effective_threshold})",
                    evidence=evidence_summary,
                    count=len(matched_entries),
                    timestamp=first_entry.timestamp,
                    remediation=rule.remediation
                ))
                alert_counter += 1

        # Sort alerts descending by severity, then by occurrence count
        alerts.sort(
            key=lambda a: (SEVERITY_ORDER.get(a.severity, 0), a.count),
            reverse=True
        )

        return alerts

    def get_mitre_matrix(self) -> List[Dict[str, Any]]:
        """Return MITRE ATT&CK coverage summary across all loaded rules."""
        matrix = []
        for r in self.rules:
            matrix.append({
                "rule_id": r.id,
                "rule_name": r.name,
                "tactic": r.mitre_tactic,
                "technique_id": r.mitre_id,
                "technique_name": r.mitre_technique,
                "severity": r.severity
            })
        return matrix

    def export_navigator_layer(
        self,
        alerts: Optional[List[Alert]] = None,
        file_path: Optional[str] = None,
        layer_name: str = "SOC Log Sentinel Coverage"
    ) -> Dict[str, Any]:
        """
        Export MITRE ATT&CK Navigator v4.5 compliant layer JSON with severity/confidence scores.
        Can export observed incident alerts or all loaded detection capabilities.
        """
        techniques = []

        if alerts is not None:
            # Aggregate alerts by technique_id and tactic
            aggregated: Dict[tuple[str, str], List[Alert]] = defaultdict(list)
            for a in alerts:
                if a.mitre_id and a.mitre_id != "T1000":
                    tactic_norm = TACTIC_NAVIGATOR_MAP.get(a.mitre_tactic.lower(), a.mitre_tactic.lower().replace(" ", "-"))
                    aggregated[(a.mitre_id, tactic_norm)].append(a)

            for (tech_id, tactic_norm), alert_list in aggregated.items():
                # Pick max severity
                max_alert = max(alert_list, key=lambda x: SEVERITY_ORDER.get(x.severity, 0))
                score, conf, color = SEVERITY_SCORE_MAP.get(max_alert.severity, (50, "0.50", "#3b82f6"))
                total_hits = sum(x.count for x in alert_list)

                techniques.append({
                    "techniqueID": tech_id,
                    "tactic": tactic_norm,
                    "score": score,
                    "color": color,
                    "comment": f"Rule: {max_alert.rule_name} ({max_alert.severity}, {total_hits} hits)",
                    "enabled": True,
                    "metadata": [
                        {"name": "severity", "value": max_alert.severity},
                        {"name": "confidence", "value": conf},
                        {"name": "rule_id", "value": max_alert.rule_id},
                        {"name": "hits", "value": str(total_hits)},
                    ]
                })
        else:
            # Export all configured detection rules as capability coverage
            for r in self.rules:
                if r.mitre_id and r.mitre_id != "T1000":
                    tactic_norm = TACTIC_NAVIGATOR_MAP.get(r.mitre_tactic.lower(), r.mitre_tactic.lower().replace(" ", "-"))
                    score, conf, color = SEVERITY_SCORE_MAP.get(r.severity, (50, "0.50", "#3b82f6"))
                    techniques.append({
                        "techniqueID": r.mitre_id,
                        "tactic": tactic_norm,
                        "score": score,
                        "color": color,
                        "comment": f"Capability: {r.name} ({r.severity})",
                        "enabled": True,
                        "metadata": [
                            {"name": "severity", "value": r.severity},
                            {"name": "confidence", "value": conf},
                            {"name": "rule_id", "value": r.id},
                        ]
                    })

        layer = {
            "name": layer_name,
            "versions": {
                "attack": "14",
                "navigator": "4.8.0",
                "layer": "4.5"
            },
            "domain": "enterprise-attack",
            "description": f"MITRE ATT&CK coverage layer generated by SOC Log Sentinel v2.0 ({len(techniques)} mapped techniques)",
            "filters": {
                "platforms": ["Windows", "Linux", "macOS", "Network"]
            },
            "sorting": 3,
            "layout": {
                "layout": "side",
                "aggregateFunction": "max",
                "showID": True,
                "showName": True,
                "showAggregateScores": True,
                "countUnscored": False
            },
            "hideDisabled": False,
            "techniques": techniques,
            "gradient": {
                "colors": ["#3b82f6", "#eab308", "#f97316", "#ef4444"],
                "minValue": 0,
                "maxValue": 100
            },
            "legendItems": [
                {"label": "Critical Severity (Score: 95)", "color": "#ef4444"},
                {"label": "High Severity (Score: 80)", "color": "#f97316"},
                {"label": "Medium Severity (Score: 60)", "color": "#eab308"},
                {"label": "Low Severity (Score: 40)", "color": "#3b82f6"},
            ]
        }

        if file_path:
            with open(file_path, "w", encoding="utf-8") as f:
                json.dump(layer, f, indent=2)

        return layer
